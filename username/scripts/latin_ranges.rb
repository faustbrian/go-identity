#!/usr/bin/env ruby
# Emits only the username policy's Latin letter ranges, never normalization data.
require 'digest'

expected = {
  'Scripts.txt' => '0eacb65169ae6eb1d399cd70826b3da15fff19f6f586eecf819b70c83b1d9b32',
  'UnicodeData.txt' => '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86',
  'DerivedCoreProperties.txt' => 'f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b'
}.freeze
abort 'usage: ruby scripts/latin_ranges.rb /path/to/unicode-15.1.0-ucd' unless ARGV.length == 1
expected.each do |name, checksum|
  abort "source checksum differs: #{name}" unless Digest::SHA256.file(File.join(ARGV[0], name)).hexdigest == checksum
end

scripts = {}
File.foreach(File.join(ARGV[0], 'Scripts.txt')) do |line|
  match = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(Latin|Inherited)\b/)
  next unless match
  (match[1].to_i(16)..(match[2] || match[1]).to_i(16)).each { |r| scripts[r] = match[3] }
end
points = []
diacritics = []
File.foreach(File.join(ARGV[0], 'UnicodeData.txt')) do |line|
  fields = line.split(';')
  r = fields[0].to_i(16)
  points << r if scripts[r] == 'Latin' && fields[2].start_with?('L')
  diacritics << r if (0x0300..0x036f).cover?(r) && fields[2] == 'Mn' && scripts[r] == 'Inherited'
end
abort 'inherited basic diacritic contract changed' unless diacritics == (0x0300..0x036f).to_a
dcp = File.read(File.join(ARGV[0], 'DerivedCoreProperties.txt'))
abort 'CGJ exclusion changed' unless dcp.match?(/^034F\s*; Default_Ignorable_Code_Point\b/)
ranges = []
points.each do |r|
  if ranges.last && ranges.last[1] + 1 == r
    ranges.last[1] = r
  else
    ranges << [r, r]
  end
end
abort 'Latin source subset changed' unless points.length == 1442 && ranges.length == 39

puts <<~'GO'
  // Code generated by scripts/latin_ranges.rb from Unicode 15.1.0; DO NOT EDIT.
  // Source digests, license, and regeneration are recorded in unicode151/README.md.
  package username

  import "sort"

  // Only General_Category L* intersect Script=Latin is owned here. NFC/full fold
  // remain the public identifier primitive's job, not a second Unicode engine.
  var latin151 = [...]struct{ lo, hi rune }{
GO
ranges.each { |lo, hi| puts "\t{0x#{lo.to_s(16)}, 0x#{hi.to_s(16)}}," }
puts <<~'GO'
  }

  func latinLetter(r rune) bool {
  	i := sort.Search(len(latin151), func(i int) bool { return latin151[i].hi >= r })
  	return i < len(latin151) && latin151[i].lo <= r
  }
GO
