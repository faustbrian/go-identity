#!/usr/bin/env ruby
# Emits the pinned operation classification; numeric defaults remain deployment
# configuration. Review every closed-default classification when updating inputs.
require 'json'
require 'digest'
abort 'usage: generate-risk-catalog.rb PUBLIC_CONTRACTS.json REFERENCE_CONFIGURATION.md' unless ARGV.length == 2
catalog_bytes = File.binread(ARGV[0])
configuration_bytes = File.binread(ARGV[1])
operations = JSON.parse(catalog_bytes).fetch('operations')
row = configuration_bytes.lines.find { |line| line.start_with?('| `struct:ref.risk.operation_matrix` |') }
abort 'risk matrix missing' unless row
classes = {'authentication'=>'Authentication', 'credential_mutation'=>'CredentialMutation', 'privileged'=>'Privileged', 'state_neutral_read'=>'StateNeutralRead'}
selection = {}
classes.each do |name, value|
  match = row.match(/`#{name} = ([^`]+)`/)
  abort "class missing: #{name}" unless match
  match[1].split(',').each do |id|
    abort 'duplicate operation classification' if selection.key?(id)
    selection[id] = value
  end
end
ids = operations.map { |operation| operation.fetch('id') }
abort 'duplicate/missing operation' if ids.uniq.length != ids.length || (selection.keys-ids).any?
# Native split commands implement the existing product flows but are absent from
# the historical umbrella catalog. Keep their explicit classifications in the
# owning risk module; updating them must not silently change pinned old rows.
native_bytes = File.binread(File.join(__dir__, '..', 'risk', 'native_operations.json'))
JSON.parse(native_bytes).each do |id, name|
  abort 'invalid native operation' unless id.match?(/\Aidentity\.[a-z0-9.-]+\z/) && classes.key?(name) && !ids.include?(id)
  operations << {'id' => id}
  selection[id] = classes.fetch(name)
end
puts "// Code generated by scripts/generate-risk-catalog.rb; DO NOT EDIT."
puts "// Owned Golib planning sources (MIT); regenerate and review all classifications."
puts "// PUBLIC_CONTRACTS.json SHA-256: #{Digest::SHA256.hexdigest(catalog_bytes)}"
puts "// REFERENCE_CONFIGURATION.md SHA-256: #{Digest::SHA256.hexdigest(configuration_bytes)}"
puts "// risk/native_operations.json SHA-256: #{Digest::SHA256.hexdigest(native_bytes)}"
puts "package risk\n\nimport \"time\"\n\nvar canonicalOperations = map[Action]ProfileClass{"
operations.sort_by { |operation| operation.fetch('id') }.each do |operation|
  id = operation.fetch('id')
  # All pinned public GET fallbacks are neutral discovery/availability reads
  # except SSO discovery, which is an authentication operation. Authorization-
  # sensitive reads and all unclassified mutations conservatively deny.
  neutral = operation.dig('transport','http_method') == 'GET' && operation.dig('authorization','access') == 'public' && id != 'identity.sso.discover'
  value = selection.fetch(id, neutral ? 'DefaultNeutralRead' : 'DefaultDeny')
  puts "\t#{id.dump}: #{value},"
end
puts "}"
puts "\n// These are selected-profile ceilings, not applied deployment defaults."
puts "var referenceProfileBounds = map[ProfileClass]profileBounds{"
classes.each do |name, value|
  profile = row.match(/`profile\.#{name} = ([^`]+)`/)&.[](1)
  abort 'profile missing' unless profile
  fields = profile.split(',').map { |field| field.split('=',2) }.to_h
  duration = lambda do |raw|
    m = raw.match(/\A([1-9][0-9]*)([smh])\z/)
    abort 'duration shape changed; review generator' unless m
    "#{m[1]} * time.#{ {'s'=>'Second','m'=>'Minute','h'=>'Hour'}.fetch(m[2]) }"
  end
  puts "\t#{value}: {window: #{duration.call(fields.fetch('window'))}, limit: #{Integer(fields.fetch('limit'))}, evidence: #{duration.call(fields.fetch('evidence_ttl'))}, counters: #{Integer(fields.fetch('max_counters'))}},"
end
puts "}"
