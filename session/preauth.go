var (
	// ErrInvalidPreAuthTransaction rejects malformed private flow state without
	// retaining origins, redirects, nonce, correlation or cookie input.
	ErrInvalidPreAuthTransaction = errors.New("session: invalid pre-auth transaction")
	// ErrPreAuthDenied is uniform for missing, different or expired binding.
	// It does not prove whether any flow exists or whether a cookie is valid.
	ErrPreAuthDenied = errors.New("session: pre-auth transaction denied")
)

// PreAuthPurpose distinguishes session-issuing login from recovery that cannot
// carry a session-lifetime choice. Unknown values deny; zero preserves login.
type PreAuthPurpose uint8

const (
	// PreAuthSessionIssuance retains the original login/linking framing and
	// requires a resolved RememberPolicy before any continuation is issued.
	PreAuthSessionIssuance PreAuthPurpose = iota
	// PreAuthPhonePasswordRecovery selects only phone password-reset initiation,
	// requires an identifier commitment and forbids every RememberPolicy.
	PreAuthPhonePasswordRecovery
)

// PreAuthIntent freezes the selected unauthenticated session-issuance/linking
// intent. IDs/actions/policy IDs are exact 1..128 visible ASCII bytes; versions
// are positive. Origin is an exact HTTPS origin (HTTP only for explicit local
// development loopback), without path/query/fragment/userinfo. CallbackURL is
// empty for explicitly no redirect, or a bounded absolute URL under the same
// transport rules, without userinfo/fragment. No normalization or allowlisting
// occurs here: trusted initiation must validate configured origins/redirects
// before creating intent. Nonce is 32 server-generated bytes, not all zero.
// Login Remember must already be resolved, never defaulted during continuation.
// Phone recovery instead selects its exact Purpose and leaves Remember zero.
// This private projection is not credential verification or policy authority.
type PreAuthIntent struct {
	TenantID                    identity.TenantID
	Action, Origin, CallbackURL string
	Nonce                       [32]byte
	Remember                    RememberPolicy
	PolicyID                    string
	PolicyVersion               uint64
	// IdentifierBinding is an optional server-derived commitment to the exact
	// canonical identifier, tenant, purpose and comparison profile. Zero retains
	// legacy unbound intent. A selected identifier-bound workflow must require
	// and compare this commitment before credential work; its presence alone is
	// not authentication. Never use plaintext identifiers or client-chosen hashes.
	IdentifierBinding [32]byte
	// Purpose is normally zero. Phone password recovery issues no session;
	// its exact action/identifier binding and absent Remember are mandatory.
	Purpose PreAuthPurpose
}

// PreAuthBinding preserves the original flow identity and timeline. ID alone
// grants no authority. IssuedAt/ExpiresAt are authoritative original UTC times;
// general configured TTL is 1..10 minutes, with the reference profile exactly
// five minutes. A continuation may not restart either time or replace intent.
type PreAuthBinding struct {
	ID                  identity.PreAuthTransactionID
	Intent              PreAuthIntent
	IssuedAt, ExpiresAt time.Time
}

// PreAuthTransactionSpec is a complete private storage projection. Cookie is
// the named-key domain-separated flow-cookie digest, never a raw bearer or a
// session lookup digest. Version is the positive durable record CAS version.
// Active/reserved/terminal state, exact reservation custody, current policy,
// one-use consumption and commit recovery remain the durable adapter's owners.
type PreAuthTransactionSpec struct {
	Binding PreAuthBinding
	Cookie  TokenDigest
	Version uint64
}

// PreAuthTransaction owns immutable structural continuation state. It is not
// authentication, an active primary record or one-use proof. Zero is invalid.
// Copies are safe for concurrent reads; no resource/goroutine is retained.
type PreAuthTransaction struct{ state *preAuthState }
type preAuthState struct{ spec PreAuthTransactionSpec }

// NewPreAuthTransaction freezes validated private storage without issuing a
// cookie or persisting a flow. Invalid input returns a zero value and redacted
// ErrInvalidPreAuthTransaction. Policy allowlists, trusted nonce provenance,
// active state and atomic one-use reservation/finalization must be independently
// checked by the owned initiation/continuation and primary adapter.
func NewPreAuthTransaction(s PreAuthTransactionSpec) (PreAuthTransaction, error) {
	if !validPreAuthBinding(s.Binding) || s.Version == 0 || s.Cookie.KeyVersion == 0 || s.Cookie.Sum == ([32]byte{}) {
		return PreAuthTransaction{}, ErrInvalidPreAuthTransaction
	}
	b := &s.Binding
	b.ID = identity.PreAuthTransactionID(strings.Clone(string(b.ID)))
	b.Intent.TenantID = identity.TenantID(strings.Clone(string(b.Intent.TenantID)))
	b.Intent.Action = strings.Clone(b.Intent.Action)
	b.Intent.Origin = strings.Clone(b.Intent.Origin)
	b.Intent.CallbackURL = strings.Clone(b.Intent.CallbackURL)
	b.Intent.PolicyID = strings.Clone(b.Intent.PolicyID)
	b.IssuedAt = b.IssuedAt.UTC()
	b.ExpiresAt = b.ExpiresAt.UTC()
	return PreAuthTransaction{state: &preAuthState{spec: s}}, nil
}

// Bindings returns an owned private scalar projection without renewing the
// timeline or remember choice. Never log it or expose it as a wire credential.
func (p PreAuthTransaction) Bindings() (PreAuthTransactionSpec, error) {
	if p.state == nil {
		return PreAuthTransactionSpec{}, ErrInvalidPreAuthTransaction
	}
	return p.state.spec, nil
}

// Check compares the complete original expected binding and independently
// computed flow-cookie digest. Now must be primary authoritative time sampled
// after locking the current record; equality at expiry denies. The earlier
// flow state is never refreshed. Success is only structural/temporal agreement:
// it cannot authenticate a subject, check current primary state or consume a
// flow. The durable owner must fence its exact version/state and finalize with
// session issuance/linking in the shared transaction. No IO or callbacks run.
func (p PreAuthTransaction) Check(now time.Time, expected PreAuthBinding, cookie TokenDigest) error {
	if p.state == nil || !validTime(now) || !validPreAuthBinding(expected) {
		return ErrPreAuthDenied
	}
	s := p.state.spec
	if !samePreAuthBinding(s.Binding, expected) || now.Before(s.Binding.IssuedAt) || !now.Before(s.Binding.ExpiresAt) || cookie.KeyVersion != s.Cookie.KeyVersion || !hmac.Equal(cookie.Sum[:], s.Cookie.Sum[:]) {
		return ErrPreAuthDenied
	}
	return nil
}

func samePreAuthBinding(a, b PreAuthBinding) bool {
	return a.ID == b.ID && a.Intent == b.Intent && a.IssuedAt.Equal(b.IssuedAt) && a.ExpiresAt.Equal(b.ExpiresAt)
}

func validPreAuthBinding(b PreAuthBinding) bool {
	if _, err := identity.ParsePreAuthTransactionID(string(b.ID)); err != nil {
		return false
	}
	i := b.Intent
	if !authorityKey(string(i.TenantID), 128) || !authorityKey(i.Action, 128) || !authorityKey(i.PolicyID, 128) || i.PolicyVersion == 0 || i.Nonce == ([32]byte{}) || !preAuthURL(i.Origin, true) || i.CallbackURL != "" && !preAuthURL(i.CallbackURL, false) {
		return false
	}
	if i.Purpose == PreAuthPhonePasswordRecovery {
		if i.Action != "identity.phone.password-reset-request" || i.Remember != (RememberPolicy{}) || i.IdentifierBinding == ([32]byte{}) {
			return false
		}
	} else {
		if i.Purpose != PreAuthSessionIssuance || i.Action == "identity.phone.password-reset-request" {
			return false
		}
		if _, err := i.Remember.Bindings(); err != nil {
			return false
		}
	}
	// Storage and cookie framing use UTC. Local years alone do not guarantee
	// that normalization stays within the supported durable timeline.
	if !validTime(b.IssuedAt) || !validTime(b.ExpiresAt) || !validTime(b.IssuedAt.UTC()) || !validTime(b.ExpiresAt.UTC()) {
		return false
	}
	ttl := b.ExpiresAt.Sub(b.IssuedAt)
	return ttl >= time.Minute && ttl <= 10*time.Minute
}

func preAuthURL(raw string, origin bool) bool {
	if !authorityKey(raw, 2048) {
		return false
	}
	u, err := url.Parse(raw)
	if err != nil || u.Opaque != "" || u.Hostname() == "" || u.User != nil || u.Fragment != "" || u.RawFragment != "" || strings.Contains(raw, "#") {
		return false
	}
	if u.Scheme != "https" {
		if u.Scheme != "http" {
			return false
		}
		switch u.Hostname() {
		case "localhost", "127.0.0.1", "::1":
		default:
			return false
		}
	}
	return !origin || (u.Path == "" && u.RawPath == "" && u.RawQuery == "" && !u.ForceQuery)
}

// PreAuthDigest derives HMAC-SHA-256 cookie lookup under the exact named key
// and complete original binding. Use a dedicated pre-auth key, not the session
// lookup/signing/envelope key. The framing starts with golib-preauth-cookie-v1
// NUL and the uint32 key version. Next come ID, tenant, action, origin, callback
// and policy strings, each with a uint16 byte length, then nonce, uint64 policy
// version, UTC RFC3339Nano issued/expiry
// strings, resolved uint8 remember choice and four uint64 nanosecond durations,
// then uint8 decoded token size and token bytes, all integers big-endian.
// With nonzero IdentifierBinding, the domain is instead
// golib-preauth-cookie-identifier-v1 NUL and its exact 32 bytes follow the four
// durations, before token size/bytes. Zero retains every legacy framing byte.
// Phone recovery instead uses golib-preauth-cookie-phone-recovery-v1 NUL,
// omits the remember choice/durations and requires the identifier commitment.
// No key fallback, raw-cookie storage, automatic disclosure, time sample or
// validity renewal occurs. Compute only from authenticated original intent;
// possession of the result is not an alternate credential or one-use proof.
func (t Token) PreAuthDigest(k DigestKey, b PreAuthBinding) (TokenDigest, error) {
	if t.state == nil {
		return TokenDigest{}, ErrInvalidToken
	}
	if k.state == nil || !validPreAuthBinding(b) {
		return TokenDigest{}, ErrInvalidPreAuthTransaction
	}
	// Token constructors guarantee canonical bounded immutable wire bytes.
	raw, _ := base64.RawURLEncoding.DecodeString(t.state.wire)
	defer clear(raw)
	// Keep the existing cookie framing byte-for-byte for unbound flows. Bound
	// flows have a separate domain so clearing the commitment cannot preserve
	// a valid original cookie (phone password-preauth's substitution boundary).
	domain := "golib-preauth-cookie-v1\x00"
	if b.Intent.IdentifierBinding != ([32]byte{}) {
		domain = "golib-preauth-cookie-identifier-v1\x00"
	}
	if b.Intent.Purpose == PreAuthPhonePasswordRecovery {
		// Recovery has no final session and must not invent login lifetimes to
		// reuse pre-auth storage. Its distinct domain omits remember entirely.
		domain = "golib-preauth-cookie-phone-recovery-v1\x00"
	}
	frame := []byte(domain)
	frame = binary.BigEndian.AppendUint32(frame, k.state.version)
	i := b.Intent
	for _, s := range []string{string(b.ID), string(i.TenantID), i.Action, i.Origin, i.CallbackURL, i.PolicyID} {
		frame = binary.BigEndian.AppendUint16(frame, uint16(len(s)))
		frame = append(frame, s...)
	}
	frame = append(frame, i.Nonce[:]...)
	frame = binary.BigEndian.AppendUint64(frame, i.PolicyVersion)
	for _, s := range []string{b.IssuedAt.UTC().Format(time.RFC3339Nano), b.ExpiresAt.UTC().Format(time.RFC3339Nano)} {
		frame = binary.BigEndian.AppendUint16(frame, uint16(len(s)))
		frame = append(frame, s...)
	}
	if i.Purpose == PreAuthSessionIssuance {
		remember, _ := i.Remember.Bindings()
		frame = append(frame, byte(remember.Choice))
		for _, d := range []time.Duration{remember.AbsoluteTTL, remember.IdleTTL, remember.RefreshAfter, remember.FreshFor} {
			frame = binary.BigEndian.AppendUint64(frame, uint64(d))
		}
	}
	if i.IdentifierBinding != ([32]byte{}) {
		frame = append(frame, i.IdentifierBinding[:]...)
	}
	frame = append(frame, byte(len(raw)))
	frame = append(frame, raw...)
	defer clear(frame)
	h := hmac.New(sha256.New, k.state.material[:k.state.size])
	_, _ = h.Write(frame)
	digest := TokenDigest{KeyVersion: k.state.version}
	copy(digest.Sum[:], h.Sum(nil))
	return digest, nil
}

